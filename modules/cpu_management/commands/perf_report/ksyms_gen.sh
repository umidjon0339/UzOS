#!/bin/sh
# =============================================================================
# ksyms_gen.sh - Turn the kernel's function list into a C table.
#
#   sh ksyms_gen.sh build/kernel.nosyms > build/ksyms.c
#
# `nm -n` lists every symbol of the linked kernel, sorted by address:
#
#     00100000 T _start          T = function (global), t = static function
#     001000a4 t setup_cpu
#
# We keep the functions (T and t) and print them as rows of ksym_table[],
# which ksyms.c (next to this script) searches. Called by the Makefile (see "linked
# twice" there); the result lives in build/, it is never edited by hand.
# =============================================================================

echo '/* Generated by modules/cpu_management/commands/perf_report/ksyms_gen.sh - do not edit. */'
echo '#include "modules/cpu_management/commands/perf_report/ksyms.h"'
echo ''
echo 'const ksym_t ksym_table[] = {'
nm -n "$1" | awk '$2 == "T" || $2 == "t" { printf "    { 0x%s, \"%s\" },\n", $1, $3 }'
echo '};'
echo 'const uint32_t ksym_count = sizeof(ksym_table) / sizeof(ksym_table[0]);'
