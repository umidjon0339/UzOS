#!/usr/bin/env python3
"""
make_font_data.py - Regenerate ../font_data.c from two free fonts.

    1. Terminus Font 4.49 (SIL Open Font License):
         https://sourceforge.net/projects/terminus-font/  -> unpack it, use ter-u16n.bdf
    2. font8x8 by Daniel Hepper (public domain):
         https://github.com/dhepper/font8x8  -> font8x8_basic.h, _ext_latin.h,
         _box.h, _block.h, _greek.h, _misc.h

    python3 make_font_data.py <download dir> ../font_data.c

The download dir must hold terminus-font-4.49.1/ and the font8x8_*.h files.
Characters are put in code page 437 order (the PC's own character set):
for each code 0-255 the script asks Python's 'cp437' codec which Unicode
character it is, and takes that glyph from the font.
"""
import re, sys

def load_bdf(path):
    glyphs, enc, rows, inbm = {}, None, [], False
    bbx = None
    ascent = descent = 0
    for line in open(path, encoding='latin1'):
        w = line.split()
        if not w: continue
        if w[0] == 'FONT_ASCENT': ascent = int(w[1])
        elif w[0] == 'FONT_DESCENT': descent = int(w[1])
        elif w[0] == 'ENCODING': enc = int(w[1])
        elif w[0] == 'BBX': bbx = list(map(int, w[1:]))
        elif w[0] == 'BITMAP': inbm, rows = True, []
        elif w[0] == 'ENDCHAR':
            inbm = False
            bw, bh, bx, by = bbx
            h = ascent + descent
            full = [0]*h
            top = ascent - (by + bh)
            for i, r in enumerate(rows):
                y = top + i
                if 0 <= y < h: full[y] = (r >> bx) if bx >= 0 else r
            glyphs[enc] = bytes(full)
        elif inbm: rows.append(int(w[0], 16) & 0xFF if len(w[0]) <= 2 else int(w[0][:2], 16))
    return glyphs

CTRL=[0,0x263A,0x263B,0x2665,0x2666,0x2663,0x2660,0x2022,0x25D8,0x25CB,0x25D9,0x2642,0x2640,0x266A,0x266B,0x263C,0x25BA,0x25C4,0x2195,0x203C,0xB6,0xA7,0x25AC,0x21A8,0x2191,0x2193,0x2192,0x2190,0x221F,0x2194,0x25B2,0x25BC]
def uni(c):
    if c < 0x20: return CTRL[c]
    if c == 0x7F: return 0x2302
    return ord(bytes([c]).decode('cp437'))
DL, OUT = sys.argv[1], sys.argv[2]
ter = load_bdf(DL + '/terminus-font-4.49.1/ter-u16n.bdf')
f8 = {}
for name, base in [('basic',0),('ext_latin',0xA0),('box',0x2500),('block',0x2580),('greek',0x390),('misc',0)]:
    try: txt = open(DL + '/font8x8_%s.h' % name).read()
    except OSError: continue
    for m in re.finditer(r'\{\s*((?:0x[0-9A-Fa-f]{2},?\s*){8})\}\s*,?\s*//\s*U\+([0-9A-Fa-f]{4})', txt):
        bs = [int(x,16) for x in re.findall(r'0x([0-9A-Fa-f]{2})', m.group(1))]
        # font8x8 stores bit 0 = leftmost pixel; VGA wants bit 7 = leftmost
        bs = [int(format(b,'08b')[::-1],2) for b in bs]
        f8.setdefault(int(m.group(2),16), bs)
def desc(c):
    u = uni(c)
    if c == 0: return 'unused'
    ch = chr(u)
    if c < 0x20 or c == 0x7F or u > 0x7E: return 'U+%04X' % u
    if ch == '\\': return "'\\\\'"
    return "'%s'" % ch
g16, g8, from_ter8 = [], [], []
for c in range(256):
    u = uni(c)
    g = list(ter.get(u, bytes(16))) if c else [0]*16
    g16.append(g)
    if c and u in f8 and (any(f8[u]) or c == 0x20 or c == 0xFF):
        g8.append(f8[u])
    else:
        g8.append([g[2*i] | g[2*i+1] for i in range(8)])   # squeeze 16 rows into 8
        if c: from_ter8.append(c)
def rows(g): return ', '.join('0x%02X' % b for b in g)
with open(OUT, 'w') as o:
    o.write('''/*
 * font_data.c - The UzOS console font, in code page 437 order.
 *
 * GENERATED by tools/make_font_data.py from two free fonts. Do not
 * edit by hand; to change an icon, edit glyphs.c instead.
 *
 *   font_uzos_8x16  Terminus Font 4.49 (ter-u16n), Copyright (C) 2020
 *                   Dimitar Toshkov Zhekov, SIL Open Font License 1.1
 *                   (see OFL.txt). Converted to CP437 order, so it is a
 *                   "Modified Version" and is not called Terminus here.
 *   font_uzos_8x8   font8x8 by Daniel Hepper, public domain; the few
 *                   characters it lacks are the 8x16 glyph squeezed to
 *                   8 rows (each new row = two old rows ORed together).
 *
 * One byte per pixel row, bit 7 = leftmost pixel. Index = character code.
 */

#include "font.h"

const uint8_t font_uzos_8x16[256][16] = {
''')
    for c in range(256):
        o.write('    { %s },  // 0x%02X %s\n' % (rows(g16[c]), c, desc(c)))
    o.write('};\n\nconst uint8_t font_uzos_8x8[256][8] = {\n')
    for c in range(256):
        o.write('    { %s },  // 0x%02X %s\n' % (rows(g8[c]), c, desc(c)))
    o.write('};\n')
print('8x8 glyphs squeezed from 8x16:', len(from_ter8), [hex(c) for c in from_ter8])
