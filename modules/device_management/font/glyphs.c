int glyphs_count(void) {
    return sizeof(icons) / sizeof(icons[0]);
}

uint8_t glyphs_get(int i, uint8_t rows[16]) {
    for (int row = 0; row < 16; row++) {
        uint8_t bits = 0;
        for (int x = 0; x < 8; x++)
            if (icons[i].rows[row][x] == '#')
                bits |= 0x80 >> x;
        rows[row] = bits;
    }
    return icons[i].code;
}
